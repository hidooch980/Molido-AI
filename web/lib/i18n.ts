const STORAGE_KEY = 'molido_lang';

/**
 * زبانِ ذخیره‌شده.
 *
 * فهرست مجاز از `LANGS` می‌آید، نه از یک شرطِ دستی.
 *
 * پیش از این، شرط `stored === 'en' || stored === 'ar'` نوشته شده بود و
 * وقتی بلوچی به `LANGS` اضافه شد، کسی این‌جا را عوض نکرد: کاربر بلوچی
 * را انتخاب می‌کرد، در حافظه ذخیره می‌شد، و موقع خواندن به فارسی
 * برمی‌گشت.  دکمه بود، کار نمی‌کرد، و هیچ خطایی هم نمی‌داد.
 */
export function getLang(): Lang {
  if (typeof window === 'undefined') {
    return 'fa';
  }

  const stored = window.localStorage.getItem(STORAGE_KEY);

  return LANGS.some((item) => item.code === stored) ? (stored as Lang) : 'fa';
}

export function setLangStorage(lang: Lang) {
  window.localStorage.setItem(STORAGE_KEY, lang);
}

export function dirFor(lang: Lang): 'rtl' | 'ltr' {
  return lang === 'en' ? 'ltr' : 'rtl';
}

export function localeFor(lang: Lang): string {
  if (lang === 'en') {
    return 'en-US';
  }

  if (lang === 'ar') {
    return 'ar-EG';
  }

  return 'fa-IR';
}

export function t(key: string, lang: Lang): string {
  const entry = DICT[key];
  if (!entry) return key;

  const direct = entry[lang];
  if (direct) return direct;

  // ترجمهٔ نبوده → زبان جایگزین.  خودِ کلید فقط وقتی برمی‌گردد که
  // هیچ‌کدام نباشند، که یعنی کلید اشتباه تایپ شده.
  const fallback = FALLBACK[lang];
  return (fallback ? entry[fallback] : undefined) ?? entry.fa ?? key;
}

/**
 * چند درصد از رابط به این زبان ترجمه شده.
 *
 * در تنظیمات نشان داده می‌شود: کاربری که بلوچی را انتخاب می‌کند باید
 * بداند بخشی از متن‌ها فارسی می‌مانند — نه اینکه فکر کند سامانه خراب
 * است.
 */
export function coverage(lang: Lang): number {
  const keys = Object.keys(DICT);
  if (!keys.length) return 0;

  const done = keys.filter((k) => Boolean(DICT[k][lang])).length;
  return Math.round((done / keys.length) * 100);
}
