-- کاتالوگِ اولیهٔ ماژول‌های سایتِ معرفی.
--
-- ⚠️ چرا مهاجرت و نه چند `INSERT` دستی روی سرور؟
--
--    دقیقاً همین اتفاق افتاد: کاتالوگِ تولید با شش `INSERT` که یک بار
--    روی سرور تایپ شد ساخته شد.  نتیجه‌اش این بود که:
--
--      • نصبِ تازه کاتالوگِ خالی داشت و صفحهٔ خرید «فهرست ماژول‌ها در
--        دسترس نیست» می‌گفت — بدونِ هیچ خطایی.
--      • `backend/test/site-sales.sh` روی هر محیطِ نو ۱۲ سنجه قرمز
--        می‌داد، و علتش نه اشکالِ کد بود نه اشکالِ آزمون.
--
--    داده‌ای که محصول بدونش کار نمی‌کند، پیکربندی نیست؛ بخشی از
--    شِماست و باید همراهش سفر کند.
--
-- ⚠️ قیمت‌ها **به ریال**اند و جای تصمیمِ تجاری‌اند نه فنی.
--
--    این‌ها همان اعدادِ کاتالوگِ فعلی‌اند.  تغییرشان از پنل انجام
--    می‌شود؛ این مهاجرت فقط نبودِ سطر را جبران می‌کند و روی قیمتِ
--    موجود دست نمی‌زند (`DO NOTHING`).

DO $$
DECLARE
  cid text;
BEGIN
  -- ⚠️ شرکتِ میزبانِ کاتالوگ همان است که `SHOP_COMPANY_ID` می‌گوید،
  --    ولی مهاجرت به محیطِ برنامه دسترسی ندارد.  پس اگر شرکتِ seed
  --    نبود، هیچ‌کاری نمی‌کنیم — ساختنِ شرکتِ جعلی بدتر از نبودِ
  --    کاتالوگ است.
  SELECT id INTO cid FROM "Company" WHERE id = 'seed-company';
  IF cid IS NULL THEN
    RAISE NOTICE 'seed-company نیست — کاتالوگِ سایت ساخته نشد';
    RETURN;
  END IF;

  INSERT INTO "SiteModule" (id, "companyId", slug, title, summary, "priceIrr", "sortOrder")
  VALUES
    ('sitemod-pos',        cid, 'pos',        'صندوق فروشگاهی',
     'بارکد، ترازو، شیفت صندوق‌دار، کالای وزنی و کار در حالت آفلاین.', 48000000, 10),
    ('sitemod-restaurant', cid, 'restaurant', 'کافه و رستوران',
     'میز و سالن، منو و رسپی، نمایشگر آشپزخانه، رزرو و تقسیم صورتحساب.', 58000000, 20),
    ('sitemod-shop',       cid, 'shop',       'فروشگاه اینترنتی',
     'کاتالوگ عمومی، سبد خرید، سفارش مشتری، نظرات خریداران و پیگیری سفارش.', 42000000, 30),
    ('sitemod-inventory',  cid, 'inventory',  'انبار و خرید',
     'چند انباره، انتقال، شمارش، بهای تمام‌شدهٔ میانگین موزون و پیشنهاد سفارش.', 36000000, 40),
    ('sitemod-accounting', cid, 'accounting', 'حسابداری',
     'دفتر کل دوطرفه، خزانه، چک، دارایی و استهلاک، و صورت‌های مالی.', 52000000, 50),
    ('sitemod-hr',         cid, 'hr',         'منابع انسانی',
     'حضور و غیاب، حقوق و دستمزد، مرخصی، آموزش و ارزیابی عملکرد.', 39000000, 60)
  ON CONFLICT ("companyId", slug) DO NOTHING;
END $$;
