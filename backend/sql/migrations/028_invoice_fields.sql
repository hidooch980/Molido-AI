-- =============================================
-- فاکتور فروش: میدان‌هایی که فرم پشتیبان لازم دارد
--
-- صندوق لمسی با «کالا، تعداد، پرداخت» کارش راه می‌افتد، ولی فاکتور
-- عمده‌فروشی این‌ها را هم می‌خواهد و تا امروز جایی برای نگه‌داشتنشان
-- نبود — پس یا در «شرح» چپانده می‌شد یا اصلاً ثبت نمی‌شد.
-- =============================================

-- ---------- ۱) رفرنس و مهلت تسویه ----------
--
-- رفرنس: شمارهٔ سفارش خریدار، شمارهٔ قرارداد، یا حوالهٔ انبار.  وقتی
-- مشتری زنگ می‌زند و می‌گوید «سفارش ۴۴۰۲ چه شد»، باید بشود روی همین
-- جست‌وجو کرد، نه اینکه دنبال متن آزاد گشت.
ALTER TABLE "Sale" ADD COLUMN IF NOT EXISTS "reference" TEXT;

-- مهلت تسویه: فروش نسیه بدون تاریخ سررسید یعنی هیچ گزارش «سررسید
-- گذشته»‌ای ممکن نیست — و همین‌جاست که پول شرکت گم می‌شود.
ALTER TABLE "Sale" ADD COLUMN IF NOT EXISTS "dueDate" DATE;

-- ---------- ۲) اضافات و کسورات ----------
--
-- کرایهٔ حمل، هزینهٔ بسته‌بندی، گرد کردن مبلغ.  اینها نه تخفیف‌اند و نه
-- مالیات؛ اگر در تخفیف چپانده شوند، هم گزارش تخفیف دروغ می‌شود و هم
-- سند حسابداری به حساب اشتباه می‌نشیند.
--
-- NUMERIC نه FLOAT: مبلغ ریالی با ممیز شناور جمع نمی‌خورد و تراز
-- حسابداری با اختلاف یک ریال می‌شکند.
ALTER TABLE "Sale" ADD COLUMN IF NOT EXISTS "additions"  NUMERIC(14,2) NOT NULL DEFAULT 0;
ALTER TABLE "Sale" ADD COLUMN IF NOT EXISTS "deductions" NUMERIC(14,2) NOT NULL DEFAULT 0;

-- منفی بودنشان یعنی کاربر جای اضافات و کسورات را عوض کرده؛ بهتر است
-- همان‌جا رد شود تا اینکه در تراز به عنوان مبلغ منفی ظاهر شود.
DO $$
BEGIN
  ALTER TABLE "Sale" ADD CONSTRAINT "sale_extras_non_negative"
    CHECK ("additions" >= 0 AND "deductions" >= 0);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- ---------- ۳) شرح ردیف ----------
--
-- «۲ متر کم داشت»، «رنگ سفارشی».  بدون این، فروشنده توضیح قلم را در
-- شرح کل فاکتور می‌نویسد و در فاکتور ده‌ردیفی معلوم نیست به کدام است.
ALTER TABLE "SaleItem" ADD COLUMN IF NOT EXISTS "note" TEXT;

-- ---------- ۴) جست‌وجوی رفرنس ----------
--
-- جزئی: فقط فاکتورهایی که رفرنس دارند.  در فروشگاه خرده‌فروشی بیشتر
-- فاکتورها رفرنس ندارند و ایندکس کامل بی‌جهت بزرگ می‌شود.
CREATE INDEX IF NOT EXISTS "sale_reference_idx"
  ON "Sale" ("companyId", "reference")
  WHERE "reference" IS NOT NULL;

-- سررسیدهای پیش رو — پرسش «چه کسی این هفته باید تسویه کند».
CREATE INDEX IF NOT EXISTS "sale_due_date_idx"
  ON "Sale" ("companyId", "dueDate")
  WHERE "dueDate" IS NOT NULL;
