-- اتصالِ سفارشِ رستوران به شیفتِ صندوق.
--
-- ⚠️ تا امروز فروشِ رستوران در مغایرت‌گیریِ صندوق **دیده نمی‌شد**.
--
--    `CashierShiftService.totals` فقط جدولِ `Sale` را می‌شمرد، و
--    سفارشِ رستوران در `RestaurantOrder` می‌نشیند.  یعنی صندوق‌دار
--    آخرِ شب پول را می‌شمرد، سامانه انتظارِ کمتری داشت، و اختلاف
--    به‌عنوان «اضافه» ثبت می‌شد.
--
--    در رستورانی که هم صندوقِ فروشگاهی دارد هم میز، این یعنی هیچ
--    مغایرتی هرگز معنا نداشت — نه کسری دیده می‌شد نه اضافه.  و
--    مغایرت‌گیریِ بی‌معنا از نبودش بدتر است: کسی به عددش تکیه می‌کند.
--
-- ⚠️ چرا سفارش به `Sale` تبدیل نشد؟
--
--    ستونِ `RestaurantOrder.saleId` از اول در شِما بود و هرگز پر نشد.
--    وسوسه این بود که همان را زنده کنیم — یک تعریف از درآمد، و همه‌چیز
--    (شیفت، دفتر کل، گزارش) رایگان درست می‌شد.
--
--    ولی `SaleItem.productId` اجباری است و اقلامِ منو کالا نیستند.
--    زنده کردنِ آن پل یعنی ساختنِ کالای جعلی برای هر غذا — که انبار،
--    بهای تمام‌شده و گزارشِ کالا را آلوده می‌کرد.  بهای بزرگ‌تری از
--    مسئله بود.
--
--    پس شیفت مستقیم شناخته می‌شود.  محدودتر است و صادقانه‌تر.

ALTER TABLE "RestaurantOrder"
  ADD COLUMN IF NOT EXISTS "shiftId" text
    REFERENCES "CashierShift"(id) ON DELETE SET NULL;

-- ⚠️ `ON DELETE SET NULL` و نه `CASCADE`.
--
--    حذفِ یک شیفت نباید سفارشِ تسویه‌شده را ببرد.  سفارش سندِ فروش
--    است؛ شیفت فقط ظرفِ شمارشِ آن شب.

CREATE INDEX IF NOT EXISTS "RestaurantOrder_shiftId_idx"
  ON "RestaurantOrder" ("shiftId") WHERE "shiftId" IS NOT NULL;
