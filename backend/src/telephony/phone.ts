/**
 * عادی‌سازی شمارهٔ تلفن ایرانی.
 *
 * جدا از `TelephonyService` است چون تابعِ خالص است: نه به پیکربندی
 * نیاز دارد نه به شبکه، پس هم مستقیم آزمون‌پذیر است و هم رابط وب
 * می‌تواند همین را استفاده کند.
 */

const PERSIAN_DIGITS = '۰۱۲۳۴۵۶۷۸۹';

/**
 * شماره را به شکل قابل شماره‌گیری درمی‌آورد.
 *
 * فاصله و خط تیره و پرانتز حذف می‌شوند.  `+98` و `0098` و `98` به `0`
 * بدل می‌شوند، چون مرکزهای داخلی با صفرِ ملی کار می‌کنند.
 *
 * برمی‌گرداند `null` اگر چیزی برای گرفتن نماند.  `null` عمدی است و از
 * رشتهٔ خالی بهتر: رشتهٔ خالی به مرکز می‌رود و خطای مبهمی می‌گیرد که
 * ربطش به شماره معلوم نیست.
 */
export function normalizePhone(raw: string | null | undefined): string | null {
  const digits = String(raw ?? '')
    .replace(/[۰-۹]/g, (d) => String(PERSIAN_DIGITS.indexOf(d)))
    .replace(/[^\d+]/g, '');

  if (!digits) return null;

  const national = digits
    .replace(/^\+98/, '0')
    .replace(/^0098/, '0')
    .replace(/^98(?=\d{10}$)/, '0');

  // کوتاه‌تر از چهار رقم یعنی داخلی یا اشتباه؛ در هر دو حالت شمارهٔ
  // بنکدار نیست.
  return national.length >= 4 ? national : null;
}
