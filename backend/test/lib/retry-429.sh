# صبرِ محترمانه پشتِ سقفِ نرخ — مشترک بین مجموعه‌ها.
#
# ⚠️ چرا لازم است؟  چون شکستش **فقط در اجرای کامل** می‌آید.
#
#    هر مجموعه تنهایی سبز است؛ ولی وقتی پشتِ سرِ هم می‌آیند، سهمیهٔ
#    `/auth/login` یا کدِ یک‌بارمصرف تمام می‌شود و مجموعهٔ بعدی چند
#    سنجهٔ ۴۲۹ می‌گیرد که هیچ‌کدام دربارهٔ موضوعِ خودش نیست.
#
#    دو بار این دام تکرار شد (`roles`، بعد `shop-takeover`)، پس این
#    بار مشترک نوشته شد تا مجموعهٔ سوم دوباره از صفر شروع نکند.
#
#   استفاده:  retry_429 POST "$A/shop/register/request-code" "$JS" "$BODY"
#   خروجی:    بدنهٔ پاسخ روی stdout؛ ۴۲۹ خودکار تکرار می‌شود.
retry_429() {
  _m=$1; _u=$2; _h=$3; _b=$4
  _hdr=$(mktemp)
  _i=0
  while [ $_i -lt 6 ]; do
    _i=$((_i + 1))
    _out=$(curl -s -D "$_hdr" -X "$_m" "$_u" ${_h:+-H "$_h"} ${_b:+-d "$_b"})
    _code=$(head -1 "$_hdr" | tr -dc '0-9' | tail -c 3)
    [ "$_code" != "429" ] && break

    # `Retry-After` را خودِ سرور می‌گوید؛ حدس زدنش یا کند است یا بی‌فایده.
    _wait=$(grep -i '^retry-after' "$_hdr" 2>/dev/null | tr -dc '0-9' | head -c 3)
    sleep "${_wait:-6}"
  done
  rm -f "$_hdr"
  printf '%s' "$_out"
}
