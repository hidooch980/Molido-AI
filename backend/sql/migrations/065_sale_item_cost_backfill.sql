-- پر کردنِ بهای تمام‌شدهٔ اقلامِ فروشِ پیش از مهاجرت ۰۴۸.
--
-- ⚠️ گزارش‌ها **نمی‌شکنند**، و همین خطرناکش می‌کند.
--
--    `reports.service` عقب‌گرد دارد:
--        COALESCE(si."unitCost", pr."purchasePrice")
--
--    پس عددی برمی‌گردد و هیچ‌چیز خطا نمی‌دهد.  ولی آن عدد بهای
--    **امروزِ** کالاست، نه بهای روزی که فروخته شد.  یعنی سودِ ناخالصِ
--    پارسال با قیمتِ خریدِ امسال حساب می‌شود.
--
--    اندازه‌گیری‌شده روی پایگاه‌دادهٔ توسعه: ۷۳۱٬۰۷۷٬۲۹۶ با عقب‌گرد در
--    برابر ۵۷٬۵۴۷٬۲۹۶ از روی بهای ثبت‌شده — بیش از دوازده برابر.
--
-- ⚠️ چرا `purchasePrice` و نه `avgCost`؟
--
--    هیچ‌کدام درست نیستند؛ بهای واقعیِ آن روز از دست رفته.  ولی
--    `purchasePrice` همان چیزی است که گزارش **همین حالا** استفاده
--    می‌کند، پس نوشتنش هیچ عددی را عوض نمی‌کند — فقط آن را
--    **ماندگار** می‌کند تا تغییرِ فردای قیمتِ خرید، سودِ گذشته را
--    جابه‌جا نکند.
--
--    این تفاوت مهم است: مهاجرت گذشته را «درست» نمی‌کند، گذشته را
--    **قفل** می‌کند.  ادعای بیشتری از این نباید کرد.

UPDATE "SaleItem" si
   SET "unitCost" = p."purchasePrice"
  FROM "Product" p
 WHERE p.id = si."productId"
   AND si."unitCost" IS NULL
   AND COALESCE(p."purchasePrice", 0) > 0;

-- ⚠️ اقلامی که کالایشان بهای خرید ندارد، تهی می‌مانند.
--
--    نوشتنِ صفر بدتر از تهی است: صفر یعنی «رایگان فروختیم» و سودِ
--    ناخالص را صددرصد نشان می‌دهد.  تهی دست‌کم صادق است و عقب‌گردِ
--    گزارش همچنان کار می‌کند.
DO $$
DECLARE
  left_null int;
BEGIN
  SELECT count(*) INTO left_null FROM "SaleItem" WHERE "unitCost" IS NULL;
  IF left_null > 0 THEN
    RAISE NOTICE 'قلم بدون بها که کالایش هم بهای خرید ندارد: %', left_null;
  END IF;
END $$;
