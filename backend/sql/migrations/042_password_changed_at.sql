-- باطل شدنِ نشست‌ها هنگام تغییر رمز.
--
-- ⚠️ از یک آزمونِ زنده آمد، نه از احتیاط.
--
--    تغییر رمز، توکنِ صادرشدهٔ پیش از آن را **باطل نمی‌کرد**.  آزمون:
--
--      ۱) کاربر وارد شد و توکن گرفت
--      ۲) رمزش را عوض کرد  ->  {"changed":true}
--      ۳) ورود با رمز قدیمی -> ۴۰۱  (درست)
--      ۴) ولی توکنِ قدیمی روی /auth/me و /users -> **۲۰۰**
--
--    عمر توکن ۷ روز است.  یعنی کسی که حسابش لو رفته، رمز را عوض
--    می‌کند، خیالش راحت می‌شود — و مهاجم تا یک هفته دسترسی دارد.
--
--    این دقیقاً برعکسِ کاری است که کاربر فکر می‌کند انجام داده.
--
-- ⚠️ چرا ستون، نه فهرستِ سیاهِ توکن‌ها؟
--
--    فهرستِ سیاه یعنی هر درخواست یک جست‌وجوی اضافه.  مقایسهٔ `iat`
--    توکن با این ستون همان کار را می‌کند و ستونش را نگهبان از قبل
--    (برای خواندن کاربر) در دست دارد.
--
--    هزینه‌اش این است که **همهٔ** نشست‌ها باطل می‌شوند، نه فقط
--    مشکوک‌ها.  برای تغییر رمز همین درست است: کسی که رمزش را عوض
--    می‌کند، معمولاً دقیقاً همین را می‌خواهد.

ALTER TABLE "User"
  ADD COLUMN IF NOT EXISTS "passwordChangedAt" timestamptz;

-- ⚠️ مقدارِ اولیه **تهی** می‌ماند، نه `now()`.
--
--    اگر `now()` بگذاریم، همهٔ کاربرانِ فعلی در لحظهٔ مهاجرت از
--    سامانه بیرون می‌افتند — وسط روز کاری، بی‌هیچ توضیحی.
--
--    تهی یعنی «هیچ‌وقت عوض نشده»، و نگهبان آن را «باطل نکن» می‌خواند.
--    از اولین تغییرِ رمز به بعد، محافظت برقرار است.

COMMENT ON COLUMN "User"."passwordChangedAt" IS
  'زمان آخرین تغییر رمز؛ توکنِ صادرشده پیش از آن باطل است.  تهی = هرگز عوض نشده.';
