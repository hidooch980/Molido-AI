#!/usr/bin/env sh
# =============================================
# پشتیبان‌گیری خودکار از دیتابیس — نگهداشت پلکانی
#
# داخل کانتینر `backup` اجرا می‌شود و طبق زمان‌بندی BACKUP_CRON کار می‌کند.
# فایل‌ها در حجم داکری `backup_data` می‌مانند تا با حذف کانتینر از بین نروند.
#
# سه اصلی که رعایت شده‌اند:
#   ۱. نوشتن در فایل موقت و تغییر نام در پایان — پشتیبانِ نیمه‌نوشته هرگز
#      نامِ نهایی نمی‌گیرد، پس بازیابی از فایل ناقص ممکن نیست.
#   ۲. تأیید سلامت با gzip -t و بررسی محتوا پیش از پذیرفتن فایل.
#   ۳. حذف نسخه‌های قدیمی فقط پس از موفقیت نسخهٔ تازه.
#
# ---------- چرا پلکانی ----------
#
# نگهداری فقط ۱۴ روز آخر یک نقطهٔ کور بزرگ دارد: خرابی‌ای که سه هفته پیش
# شروع شده — یک قیمت غلط، یک حذف اشتباه، یک باگ که آرام داده را خراب
# می‌کند — وقتی کشف می‌شود که هیچ نسخهٔ سالمی از پیش از آن نمانده.
#
# پس سه لایه:
#   روزانه  — برای اشتباه امروز و دیروز
#   هفتگی   — برای چیزی که این ماه خراب شده
#   ماهانه  — برای اختلاف حسابداری و ممیزی مالیاتی
#
# لایه‌های بالاتر با **پیوند سخت** ساخته می‌شوند نه کپی: همان فایل است با
# نام دیگر، پس فضای اضافه نمی‌گیرد.  حذف نسخهٔ روزانه هم داده را نمی‌برد
# چون تا وقتی یک پیوند بماند، فایل روی دیسک هست.
# =============================================
set -eu

DIR="${BACKUP_DIR:-/backups}"
KEEP_DAYS="${BACKUP_KEEP_DAYS:-14}"
KEEP_WEEKS="${BACKUP_KEEP_WEEKS:-8}"
KEEP_MONTHS="${BACKUP_KEEP_MONTHS:-12}"

STAMP="$(date +%Y%m%d-%H%M%S)"
TMP="$DIR/.partial-$STAMP.sql.gz"
OUT="$DIR/daily/molido-$STAMP.sql.gz"

mkdir -p "$DIR/daily" "$DIR/weekly" "$DIR/monthly"

log() { echo "[backup $(date '+%Y-%m-%d %H:%M:%S')] $1"; }

log "شروع پشتیبان‌گیری از $PGDATABASE"

# --clean --if-exists تا فایل روی دیتابیسِ موجود هم قابل بازیابی باشد.
if ! pg_dump \
      --host="$PGHOST" --port="${PGPORT:-5432}" \
      --username="$PGUSER" --dbname="$PGDATABASE" \
      --clean --if-exists --no-owner --no-privileges \
    | gzip -9 > "$TMP"; then
  log "✗ pg_dump شکست خورد"
  rm -f "$TMP"
  exit 1
fi

# فایل خراب بدتر از نبودِ فایل است: تا وقتی صحتش تأیید نشود نام نهایی نمی‌گیرد.
if ! gzip -t "$TMP" 2>/dev/null; then
  log "✗ فایل پشتیبان سالم نیست — دور انداخته شد"
  rm -f "$TMP"
  exit 1
fi

SIZE="$(wc -c < "$TMP")"
if [ "$SIZE" -lt 1024 ]; then
  log "✗ پشتیبان مشکوک به خالی بودن ($SIZE بایت) — دور انداخته شد"
  rm -f "$TMP"
  exit 1
fi

# اندازه و سلامت gzip می‌گویند فایل کامل است، نه اینکه **داده** دارد.
# یک dump از دیتابیس خالی هم gzip سالمی است.  وجود جدول اصلی را می‌سنجیم.
if ! gzip -cd "$TMP" | grep -q 'CREATE TABLE public\."Company"'; then
  log "✗ پشتیبان جدول‌های اصلی را ندارد — دور انداخته شد"
  rm -f "$TMP"
  exit 1
fi

mv "$TMP" "$OUT"
log "✓ روزانه: $(basename "$OUT") — $((SIZE / 1024)) کیلوبایت"

# ---------- ارتقا به هفتگی و ماهانه ----------
#
# جمعه پایان هفتهٔ کاری ایران است، پس نسخهٔ هفتگی همان جمعه گرفته می‌شود:
# پشتیبانِ پایان هفته، وضعیتِ بسته‌شدهٔ آن هفته را دارد.
#
# ماهانه روی اول ماه میلادی است نه شمسی: تبدیل تقویم در پوستهٔ کانتینر
# ریسک بی‌جهت به مسیر پشتیبان‌گیری اضافه می‌کند، و آنچه اهمیت دارد داشتنِ
# «حدوداً یکی در ماه» است، نه انطباق دقیق با دورهٔ مالی.
promote() {
  tier="$1"
  name="$2"
  target="$DIR/$tier/$name"

  [ -e "$target" ] && return 0

  # پیوند سخت؛ اگر سیستم فایل اجازه نداد، کپی.
  if ln "$OUT" "$target" 2>/dev/null || cp "$OUT" "$target"; then
    log "✓ $tier: $name"
  else
    log "⚠️ ارتقا به $tier ناموفق بود"
  fi
}

# %u در busybox: ۱=دوشنبه … ۵=جمعه … ۷=یکشنبه
[ "$(date +%u)" = "5" ] && promote weekly "molido-week-$(date +%Y-W%V).sql.gz"
[ "$(date +%d)" = "01" ] && promote monthly "molido-month-$(date +%Y-%m).sql.gz"

# ---------- پاکسازی ----------
#
# فقط پس از موفقیت؛ وگرنه یک شبِ خراب می‌تواند همهٔ نسخه‌های سالم را هم
# ببرد.  هر لایه مستقل هرس می‌شود.
prune() {
  tier="$1"
  days="$2"
  count="$(find "$DIR/$tier" -name '*.sql.gz' -type f -mtime "+$days" -print -delete 2>/dev/null | wc -l)"
  [ "$count" -gt 0 ] && log "$tier: $count نسخهٔ قدیمی حذف شد"
  return 0
}

prune daily "$KEEP_DAYS"
prune weekly "$((KEEP_WEEKS * 7))"
prune monthly "$((KEEP_MONTHS * 31))"

# ---------- خلاصه ----------
# عددی که مدیر باید ببیند: چند نسخه داریم و از چه زمانی.
D="$(find "$DIR/daily"   -name '*.sql.gz' -type f | wc -l)"
W="$(find "$DIR/weekly"  -name '*.sql.gz' -type f | wc -l)"
M="$(find "$DIR/monthly" -name '*.sql.gz' -type f | wc -l)"
TOTAL="$(du -sh "$DIR" 2>/dev/null | cut -f1)"

log "موجودی: $D روزانه، $W هفتگی، $M ماهانه — مجموع $TOTAL"
