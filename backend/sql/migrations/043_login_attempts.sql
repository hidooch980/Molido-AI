-- ثبتِ تلاش‌های ورود، قفلِ موقتِ حساب، و «خروج از همهٔ دستگاه‌ها».
--
-- هر سه از یک نیاز می‌آیند: تا امروز حملهٔ حدسِ رمز **هیچ ردی**
-- نمی‌گذاشت.  سقفِ نرخ جلویش را می‌گرفت ولی چیزی ثبت نمی‌شد، پس
-- نه می‌شد فهمید کسی تلاش کرده، نه بعداً بررسی کرد.

-- ⚠️ این جدول عمداً `companyId` **ندارد**.
--
--    ورود پیش از آنکه شرکت معلوم شود اتفاق می‌افتد — و مهاجمی که
--    ایمیل‌ها را حدس می‌زند، اصلاً به هیچ شرکتی تعلق ندارد.
--
--    اگر `companyId` می‌گذاشتیم، تلاش‌های ناموفقِ ایمیلِ ناشناس یا
--    باید تهی می‌ماندند (که RLS را بی‌معنی می‌کند) یا اصلاً ثبت
--    نمی‌شدند — یعنی دقیقاً همان چیزی که می‌خواهیم ببینیم، ثبت
--    نمی‌شد.
--
--    محافظتش در لایهٔ API است: فقط مدیر می‌بیندش.

CREATE TABLE IF NOT EXISTS "LoginAttempt" (
  id          text PRIMARY KEY,
  -- ⚠️ ایمیل **همان‌طور که وارد شده** ذخیره می‌شود، نه شناسهٔ کاربر.
  --
  --    تلاش روی ایمیلی که وجود ندارد هم باید ثبت شود: الگوی حدس‌زدن
  --    دقیقاً همان‌جا دیده می‌شود.
  email       text NOT NULL,
  ip          text,
  "userAgent" text,
  success     boolean NOT NULL,
  -- علتِ شکست — برای تفکیکِ «رمز غلط» از «حساب قفل» از «غیرفعال».
  reason      text,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

-- پرس‌وجوی همیشگی: «چند تلاشِ ناموفق برای این ایمیل در بازهٔ اخیر؟»
CREATE INDEX IF NOT EXISTS "LoginAttempt_email_time_idx"
  ON "LoginAttempt" (email, "createdAt" DESC);

-- برای پاک‌سازیِ دوره‌ای و گزارشِ بازه‌ای.
CREATE INDEX IF NOT EXISTS "LoginAttempt_time_idx"
  ON "LoginAttempt" ("createdAt" DESC);

GRANT SELECT, INSERT, DELETE ON "LoginAttempt" TO molido_app;

-- ---------------------------------------------------------------- قفل

-- ⚠️ قفل **موقت** است، نه دائمی.
--
--    قفلِ دائمی یعنی مهاجم می‌تواند با ده تلاشِ عمداً غلط، حسابِ هر
--    کسی را ببندد — یعنی خودش می‌شود ابزارِ حمله.
--
--    قفلِ کوتاه، حدسِ رمز را غیرعملی می‌کند بی‌آنکه سلاحِ مهاجم شود.
ALTER TABLE "User"
  ADD COLUMN IF NOT EXISTS "lockedUntil" timestamptz;

COMMENT ON COLUMN "User"."lockedUntil" IS
  'تا این لحظه ورود پذیرفته نمی‌شود.  تهی = قفل نیست.';

-- ------------------------------------------- خروج از همهٔ دستگاه‌ها

-- ⚠️ چرا ستونِ جدا، نه استفادهٔ دوباره از `passwordChangedAt`؟
--
--    معنایشان فرق دارد.  «رمزم را عوض کردم» و «می‌خواهم همه‌جا خارج
--    شوم» دو کارِ متفاوت‌اند، و کاربر ممکن است دومی را بخواهد بی‌آنکه
--    رمزش را عوض کند (مثلاً گوشی‌اش را جا گذاشته).
--
--    یکی کردنشان یعنی رابط مجبور شود برای «خروج از همه‌جا» رمز عوض
--    کند — که کاربر را وامی‌دارد رمزِ تازه‌ای بسازد و به خاطر بسپارد،
--    بی‌هیچ دلیلی.
ALTER TABLE "User"
  ADD COLUMN IF NOT EXISTS "sessionsRevokedAt" timestamptz;

COMMENT ON COLUMN "User"."sessionsRevokedAt" IS
  'خروج دستی از همهٔ دستگاه‌ها؛ توکنِ صادرشده پیش از آن باطل است.';
