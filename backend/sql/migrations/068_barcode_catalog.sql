-- فهرستِ مشترکِ بارکد — «هر جنسی که ثبت شود، برای بعدی‌ها آماده است».
--
-- ⚠️ چرا فهرستِ مشترک، و نه فقط پایگاه‌های جهانی؟
--
--    سنجیده شد: Open Food Facts بارکدِ کوکاکولا را با نام و تصویر
--    می‌دهد، ولی سه بارکدِ ایرانیِ `626…` را «product not found».
--    یعنی ساختنِ این قابلیت فقط روی منابعِ جهانی، برای فروشگاهِ
--    ایرانی قابلیتی می‌ساخت که در نمایش کار می‌کند و در عمل نه.
--
--    راهِ درست: هر کالایی که **یک** فروشگاه ثبت می‌کند، برای
--    فروشگاه‌های بعدی آماده باشد.  سامانه با هر ثبت باهوش‌تر می‌شود،
--    و منابعِ جهانی فقط عقب‌گرد می‌مانند.
--
-- ⚠️ این جدول **بین‌شرکتی** است و RLS ندارد — و این تصمیم عمدی است.
--
--    همهٔ جدول‌های دیگر با `companyId` جدا می‌شوند.  اینجا نه، چون
--    کلِ فایده‌اش اشتراک است.
--
--    ولی آنچه به اشتراک می‌رود **دقیقاً** محدود است: بارکد، نام،
--    برند، واحد و تصویر.  یعنی همان چیزی که روی خودِ بستهٔ کالا در
--    قفسهٔ فروشگاه نوشته شده و راز نیست.
--
--    ⚠️ قیمت، موجودی، تأمین‌کننده و بهای خرید **هرگز** اینجا
--       نمی‌آیند.  آن‌ها اسرارِ تجاریِ هر فروشگاه‌اند و لو رفتنشان
--       یعنی رقیب حاشیهٔ سودت را بداند.

CREATE TABLE IF NOT EXISTS "BarcodeCatalog" (
  -- ⚠️ خودِ بارکد کلیدِ اصلی است.
  --
  --    کلیدِ مصنوعی یعنی امکانِ دو ردیف برای یک بارکد، و آن‌وقت
  --    «کدام درست است؟» سؤالی می‌شود که جواب ندارد.
  barcode     text PRIMARY KEY,

  name        text NOT NULL,
  brand       text,
  unit        text,
  category    text,

  -- نشانیِ **محلیِ** تصویر پس از دانلود (`/uploads/...`).
  "imageUrl"  text,

  -- ⚠️ منبع ثبت می‌شود تا بشود اعتماد را وزن داد.
  --
  --    'LOCAL'  — کاربری در همین سامانه ثبتش کرده
  --    'OFF'    — Open Food Facts
  --    هر منبعِ تازه‌ای که اضافه شود، نامِ خودش را می‌گیرد.
  source      text NOT NULL DEFAULT 'LOCAL',

  -- ⚠️ چند بار دیده شده — نشانهٔ درستی.
  --
  --    بارکدی که ده فروشگاه با همان نام ثبتش کرده‌اند، از بارکدی که
  --    یکی ثبت کرده مطمئن‌تر است.  بدونِ این عدد، غلطِ تایپیِ اولین
  --    نفر برای همیشه می‌ماند.
  "seenCount" integer NOT NULL DEFAULT 1,

  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "BarcodeCatalog_barcode_shape" CHECK (barcode ~ '^[0-9]{8,14}$')
);

-- جست‌وجوی نامی برای وقتی بارکد نیست.
CREATE INDEX IF NOT EXISTS "BarcodeCatalog_name_idx" ON "BarcodeCatalog" (lower(name));

-- ⚠️ خواندن برای همه، نوشتن هم — ولی سرویس تنها راهِ نوشتن است.
--
--    `molido_app` به این جدول مستقیم دسترسی دارد چون RLS ندارد؛
--    محافظت در لایهٔ سرویس است که فقط میدان‌های عمومی را می‌نویسد.
GRANT SELECT, INSERT, UPDATE ON "BarcodeCatalog" TO molido_app;
