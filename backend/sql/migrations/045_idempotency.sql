-- کلیدِ یکتاسازیِ درخواست — برای نوشتنِ آفلاین.
--
-- ⚠️ چرا لازم شد؟
--
--    انباردار در انبارِ بی‌آنتن فاکتور ثبت می‌کند و درخواست در صفِ
--    مرورگر می‌نشیند.  صف، تلاشِ دوباره می‌کند.
--
--    حالا فرض کنید درخواست به سرور رسید، فاکتور ساخته شد، موجودی
--    بالا رفت و سندِ حسابداری خورد — ولی پاسخ در راهِ برگشت گم شد.
--    صف خبر ندارد و دوباره می‌فرستد.  نتیجه: **دو فاکتور، دو برابر
--    موجودی، دو سند**.
--
--    این خطای مالی است، نه آزارِ کاربر.  انبارگردانیِ بعدی اختلاف را
--    نشان می‌دهد ولی هیچ‌کس نمی‌فهمد چرا.
--
-- ⚠️ کلید را **کلاینت** پیش از رفتن به صف می‌سازد، نه سرور.
--
--    اگر سرور می‌ساخت، هر تلاشِ دوباره کلیدِ تازه‌ای می‌گرفت و دقیقاً
--    همان مشکل باقی می‌ماند.  کلید باید به «آن فاکتورِ مشخص» بچسبد،
--    نه به «آن درخواست».

-- ⚠️ `text` است، نه `uuid`.
--
--    شناسه‌ها در این پروژه متن‌اند («seed-company»، «seed-p3»)، نه
--    UUID.  ستونِ uuid درخواست را با ۵۰۰ می‌شکست — و آزمون گرفتش.
CREATE TABLE IF NOT EXISTS "IdempotencyKey" (
  id           text PRIMARY KEY,
  "companyId"  text NOT NULL,
  key          text NOT NULL,
  endpoint     text NOT NULL,
  -- تهی یعنی «هنوز در حال اجراست»؛ پس از پایان پر می‌شود.
  response     jsonb,
  "createdAt"  timestamptz NOT NULL DEFAULT now()
);

-- ⚠️ یکتایی شاملِ `companyId` است.
--
--    بدونِ آن، شرکتِ الف با حدس زدنِ کلیدِ شرکتِ ب پاسخِ فاکتورِ او را
--    می‌گرفت — یعنی نشتِ داده از راهِ کلیدِ تکراری.
CREATE UNIQUE INDEX IF NOT EXISTS "IdempotencyKey_company_key_uniq"
  ON "IdempotencyKey" ("companyId", key);

-- برای پاک‌سازیِ دوره‌ایِ کلیدهای کهنه.
CREATE INDEX IF NOT EXISTS "IdempotencyKey_createdAt_idx"
  ON "IdempotencyKey" ("createdAt");

COMMENT ON TABLE "IdempotencyKey" IS
  'کلیدِ یکتاسازیِ نوشتن؛ تلاشِ دوبارهٔ صفِ آفلاین نباید رکوردِ تکراری بسازد.';

COMMENT ON COLUMN "IdempotencyKey".response IS
  'پاسخِ اولین اجرا.  تهی = هنوز در حال اجراست؛ تلاشِ هم‌زمان باید ۴۰۹ بگیرد.';
