/**
 * قرارداد درگاه پرداخت — یک رابط، چند ارائه‌دهنده.
 *
 * ⚠️ چرا لایهٔ آداپتور، و نه صدا زدنِ مستقیمِ زرین‌پال؟
 *
 *    درگاه‌های ایرانی زیاد عوض می‌شوند: قرارداد تمام می‌شود، کارمزد
 *    بالا می‌رود، یا سرویس چند روز می‌خوابد.  اگر نامِ زرین‌پال در
 *    `shop.service.ts` بنشیند، عوض کردنش یعنی دست بردن در مسیرِ
 *    تسویه — همان جایی که کمترین اشتباه پول را جابه‌جا می‌کند.
 *
 *    با این رابط، افزودنِ درگاه تازه یعنی یک فایلِ تازه و یک سطر در
 *    `payment.module.ts`.  مسیرِ تسویه دست‌نخورده می‌ماند.
 *
 * ⚠️ مبلغ همیشه **ریال** است، عدد صحیح.
 *
 *    بعضی درگاه‌ها تومان می‌خواهند و بعضی ریال.  تبدیل، کارِ آداپتور
 *    است نه فراخوان — وگرنه روزی یکی فراموش می‌کند و مشتری ده برابر
 *    پرداخت می‌کند.
 */

/** درخواستِ آغازِ پرداخت. */
export type PaymentRequest = {
  /** مبلغ به **ریال**، عدد صحیح. */
  amount: number;
  /** شمارهٔ سفارش — در پنلِ درگاه دیده می‌شود. */
  orderNo: string;
  /** نشانی‌ای که درگاه کاربر را پس از پرداخت به آن برمی‌گرداند. */
  callbackUrl: string;
  description?: string;
  mobile?: string | null;
  email?: string | null;
};

/** پاسخِ آغازِ پرداخت. */
export type PaymentStartResult = {
  ok: boolean;
  /** نشانی‌ای که کاربر باید به آن فرستاده شود. */
  redirectUrl?: string;
  /**
   * شناسهٔ درگاه برای این تراکنش.
   *
   * ⚠️ باید ذخیره شود، وگرنه تأیید ممکن نیست: درگاه هنگام بازگشت
   *    همین را می‌فرستد و ما باید بدانیم مالِ کدام سفارش است.
   */
  reference?: string;
  error?: string;
  /** درست وقتی کلید تنظیم نشده و پرداخت واقعی رخ نداده. */
  simulated?: boolean;
};

/** نتیجهٔ تأییدِ پرداخت پس از بازگشت از درگاه. */
export type PaymentVerifyResult = {
  ok: boolean;
  /** شمارهٔ پیگیریِ نهایی — همان که به مشتری نشان داده می‌شود. */
  trackingCode?: string;
  /** مبلغی که درگاه می‌گوید واقعاً پرداخت شده، به ریال. */
  paidAmount?: number;
  error?: string;
  simulated?: boolean;
};

/**
 * هر درگاه این را پیاده می‌کند.
 *
 * ⚠️ `verify` باید **مبلغ** را هم برگرداند، نه فقط موفق/ناموفق.
 *
 *    بدون آن، مهاجم می‌تواند سفارشِ ده‌میلیونی را با پرداختِ هزار
 *    تومانی تأیید کند: کدِ پیگیری معتبر است و ما فرض می‌کنیم درست
 *    پرداخت شده.  تطبیقِ مبلغ در سرویس انجام می‌شود.
 */
export interface PaymentGateway {
  /** نامِ کوتاه و ماشین‌خوان — در `paymentRef` و لاگ می‌نشیند. */
  readonly name: string;

  /** آیا کلیدها تنظیم شده‌اند؟  اگر نه، سرویس حالتِ شبیه‌سازی می‌رود. */
  isConfigured(): boolean;

  start(request: PaymentRequest): Promise<PaymentStartResult>;

  /**
   * @param reference شناسه‌ای که هنگام `start` گرفتیم
   * @param amount مبلغِ موردِ انتظار به ریال — برای تطبیق
   */
  verify(reference: string, amount: number): Promise<PaymentVerifyResult>;
}
