-- =============================================
-- منبعِ هر متن بلوچی ثبت می‌شود
--
-- تا امروز `VoicePhrase.textTarget` فقط یک رشته بود و سامانه هیچ راهی
-- نداشت بفهمد آن رشته از کجا آمده:
--
--   ترجمهٔ حرفه‌ای واژه‌نامهٔ CC-BY-4.0 گوگل؟
--   وام‌واژهٔ فارسی که عمداً فارسی مانده؟
--   یا حدسِ ماشین که هیچ آدمی ندیده؟
--
-- هر سه در پایگاه داده یک شکل داشتند.  یعنی وقتی ضبط شروع شود و مدل
-- آموزش ببیند، حدسِ اشتباه دقیقاً مثل ترجمهٔ درست وارد مدل می‌شود و
-- هیچ‌جا رد نمی‌گذارد.
--
-- مقادیر:
--
--   GATITOS    ترجمهٔ حرفه‌ای؛ سرواژه‌اش عیناً در واژه‌نامه هست.
--   LOANWORD   عمداً فارسی مانده.  «کارت» و «چاپ» واژهٔ سنتی بلوچی
--              ندارند و گویشور هم همان فارسی را می‌گوید — همان تصمیمی
--              که برای نام کالا گرفته شد (مهاجرت ۰۳۴).
--   DERIVED    از اجزای تأییدشده ساخته شده.  «پنچ‌سد» از «پنچ» و «سد»
--              که هر دو در واژه‌نامه‌اند.
--   UNVERIFIED حدسِ ماشین.  **آموزش با این قفل است.**
--
-- ⚠️ پیش‌فرض عمداً `UNVERIFIED` است، نه `GATITOS`.
--
--    اگر پیش‌فرض «تأییدشده» بود، هر سطری که کسی بدون فکر اضافه کند
--    خودبه‌خود معتبر شمرده می‌شد — و این ستون به‌جای محافظت، پوششِ
--    اطمینانِ کاذب می‌داد.  بارِ اثبات باید روی کسی باشد که ادعا
--    می‌کند، نه روی کسی که شک دارد.
-- =============================================

ALTER TABLE "VoicePhrase"
  ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'UNVERIFIED';

ALTER TABLE "VoicePhrase"
  DROP CONSTRAINT IF EXISTS "VoicePhrase_source_check";

ALTER TABLE "VoicePhrase"
  ADD CONSTRAINT "VoicePhrase_source_check"
  CHECK (source = ANY (ARRAY['GATITOS', 'LOANWORD', 'DERIVED', 'UNVERIFIED']));

-- نام کالا از اول قرار بود فارسی بماند (مهاجرت ۰۳۴): صندوق‌دار بلوچ هم
-- «شامپو» را «شامپو» می‌گوید.  پس وام‌واژه است، نه حدس.
UPDATE "VoicePhrase"
   SET source = 'LOANWORD'
 WHERE kind = 'PRODUCT'
   AND "textTarget" IS NOT NULL
   AND "textTarget" = "textFa";

COMMENT ON COLUMN "VoicePhrase".source IS
  'منبع متن: GATITOS (ترجمهٔ حرفه‌ای) · LOANWORD (عمداً فارسی) · DERIVED (از اجزای تأییدشده) · UNVERIFIED (حدس ماشین — آموزش قفل)';
