/**
 * نقشهٔ «ساختار» — چه چیزی پشتیبان گرفته می‌شود و چه چیزی هرگز.
 *
 * ⚠️ فهرستِ **سفیدِ ستونی**، نه `SELECT *`.
 *
 *    وسوسه‌اش هست که کلِ سطر برداشته شود.  ولی `TaxSetting` ستونِ
 *    `privateKeyPem` دارد — کلیدِ خصوصیِ سامانهٔ مؤدیان — و
 *    `PosTerminal` شماره شبا و `merchantId` دارد.  یک `SELECT *`
 *    این‌ها را در فایلی می‌گذاشت که کاربر ایمیلش می‌کند.
 *
 *    و بدتر: ستونی که **فردا** اضافه شود، خودبه‌خود داخل فایل
 *    می‌رفت.  فهرستِ سفید یعنی ستونِ تازه تا وقتی کسی عمداً
 *    اضافه‌اش نکند بیرون می‌ماند.
 *
 * ⚠️ ماندهٔ حساب و صندوق **ساختار نیست**.
 *
 *    `Account.balance` و `CashBox.balance` از تراکنش‌ها می‌آیند.
 *    بردنشان به نصبِ تازه یعنی دفتری که از روزِ اول نامتراز است —
 *    ماندهٔ بدونِ سندِ پشتیبان.  ساختار می‌رود، مانده نه.
 *
 * ⚠️ ترتیب **اهمیت دارد** و به‌هم زدنش بی‌صدا خراب می‌کند.
 *
 *    `Warehouse` به `Branch` ارجاع می‌دهد و `Account` به والدِ خودش.
 *    اگر انبار پیش از شعبه بیاید، کلیدِ خارجی می‌شکند — یا بدتر،
 *    `branchId` تهی می‌ماند و کسی متوجه نمی‌شود.
 */

export type StructureTable = {
  /** نامِ جدول در پایگاه‌داده. */
  table: string;
  /** برچسبِ فارسی برای گزارشِ کاربر. */
  label: string;
  /**
   * ستون‌هایی که بیرون می‌روند.  هر چیزِ دیگری — از جمله ستونِ
   * تازه‌ای که فردا اضافه شود — بیرون می‌ماند.
   */
  columns: string[];
  /**
   * کلیدِ طبیعی برای تطبیق هنگام بازیابی.
   *
   * ⚠️ `id` **نیست**، و این عمدی است.  شناسهٔ نصبِ مبدأ در نصبِ مقصد
   *    معنایی ندارد؛ اگر با `id` تطبیق می‌دادیم، هر بازیابی رکوردِ
   *    تکراری می‌ساخت و دستهٔ «نوشیدنی» دو بار در فهرست می‌نشست.
   */
  key: string[];
  /** ارجاع‌هایی که باید به شناسهٔ **مقصد** ترجمه شوند. */
  refs?: Record<string, string>;
  /** ارجاع به خودِ همان جدول (سلسله‌مراتب). */
  selfRef?: string;
};

