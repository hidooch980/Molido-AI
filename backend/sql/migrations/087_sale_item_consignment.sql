-- فروشِ کالای امانیِ گرفته‌شده از صندوق.
--
-- ⚠️ تا امروز ممکن نبود، و در `consignment.service.ts` صریح نوشته شده
--    بود: کالای امانیِ گرفته‌شده به `Inventory` اضافه نمی‌شود (چون مالِ
--    ما نیست و نباید در ترازنامه بنشیند)، پس صندوق آن را «موجود نیست»
--    می‌دید.
--
--    یعنی فروشنده‌ای که جنسِ امانی گرفته، برای فروختنش باید از مسیرِ
--    «تسویهٔ امانی» می‌رفت — که نه رسید می‌دهد، نه در شیفتِ صندوق
--    می‌نشیند، نه مالیات می‌خورد.
--
-- ---------- چرا یک ستون، و نه یک جدولِ رابط ----------
--
-- ⚠️ این ستون **نشانه**ای است که به هر مسیرِ پایین‌دستی می‌گوید این سطر
--    چه‌طور تأمین شده.  دقیقاً همان نقشی که `unitCost` بازی می‌کند.
--
--    بدونِ آن، مرجوعی نمی‌داند این قلم را باید به `Inventory` برگرداند
--    (که هرگز آن‌جا نبوده) یا به امانی — و انتخابِ غلط، موجودی‌ای
--    می‌سازد که وجود ندارد.
ALTER TABLE "SaleItem"
  ADD COLUMN IF NOT EXISTS "consignmentItemId" text
    REFERENCES "ConsignmentItem"(id) ON DELETE RESTRICT;

COMMENT ON COLUMN "SaleItem"."consignmentItemId" IS
  'اگر پر باشد، این قلم از امانیِ گرفته‌شده فروخته شده: از Inventory کم نشده و بهایش در سندِ ConsignmentInSettle خورده، نه در SaleCogs';

-- ⚠️ `ON DELETE RESTRICT` عمدی است.
--
--    اگر `CASCADE` بود، حذفِ یک سندِ امانی سطرِ فاکتورِ فروش را هم
--    می‌برد — یعنی فاکتوری که به دستِ مشتری رفته و مالیاتش رفته، بی‌صدا
--    ناقص می‌شد.

CREATE INDEX IF NOT EXISTS "SaleItem_consignmentItem_idx"
  ON "SaleItem" ("consignmentItemId")
  WHERE "consignmentItemId" IS NOT NULL;
