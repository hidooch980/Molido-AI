-- کاتالوگِ اولیهٔ ماژول‌های سایتِ معرفی.
--
-- ⚠️ چرا مهاجرت و نه چند `INSERT` دستی روی سرور؟
--
--    دقیقاً همین اتفاق افتاد: کاتالوگِ تولید با شش `INSERT` که یک بار
--    روی سرور تایپ شد ساخته شد.  نتیجه‌اش این بود که:
--
--      • نصبِ تازه کاتالوگِ خالی داشت و صفحهٔ خرید «فهرست ماژول‌ها در
--        دسترس نیست» می‌گفت — بدونِ هیچ خطایی.
--      • `backend/test/site-sales.sh` روی هر محیطِ نو ۱۲ سنجه قرمز
--        می‌داد، و علتش نه اشکالِ کد بود نه اشکالِ آزمون.
--
--    داده‌ای که محصول بدونش کار نمی‌کند، پیکربندی نیست؛ بخشی از
--    شِماست و باید همراهش سفر کند.
--
-- ⚠️ قیمت‌ها **به ریال**اند و جای تصمیمِ تجاری‌اند نه فنی.
--
--    این‌ها همان اعدادِ کاتالوگِ فعلی‌اند.  تغییرشان از پنل انجام
--    می‌شود؛ این مهاجرت فقط نبودِ سطر را جبران می‌کند و روی قیمتِ
--    موجود دست نمی‌زند (`DO NOTHING`).

DO $$
DECLARE
  cid text;
BEGIN
  -- ⚠️ شرکتِ میزبانِ کاتالوگ همان است که `SHOP_COMPANY_ID` می‌گوید،
  --    ولی مهاجرت به محیطِ برنامه دسترسی ندارد.  پس اگر شرکتِ seed
  --    نبود، هیچ‌کاری نمی‌کنیم — ساختنِ شرکتِ جعلی بدتر از نبودِ
  --    کاتالوگ است.
  SELECT id INTO cid FROM "Company" WHERE id = 'seed-company';
  IF cid IS NULL THEN
    RAISE NOTICE 'seed-company نیست — کاتالوگِ سایت ساخته نشد';
    RETURN;
  END IF;

  -- ⚠️ اسلاگ‌ها و قیمت‌ها **دقیقاً** همان کاتالوگِ تولیدند.
  --
  --    نسخهٔ اولِ همین مهاجرت اعدادِ خودم را داشت و اسلاگِ انبار را
  --    `inventory` نوشته بود، در حالی که تولید `warehouse` داشت.
  --    `ON CONFLICT (companyId, slug) DO NOTHING` شش ردیفِ موجود را
  --    حفظ کرد ولی `inventory` را **افزود** — و صفحهٔ فروش دو ردیفِ
  --    «انبار و خرید» با دو قیمتِ متفاوت نشان داد.
  --
  --    درسش: مهاجرتِ داده‌ای که با دادهٔ دستیِ موجود هم‌تراز نشده،
  --    تعارض را حل نمی‌کند — تکثیرش می‌کند.  و `DO NOTHING` این را
  --    بی‌صدا انجام می‌دهد.
  INSERT INTO "SiteModule" (id, "companyId", slug, title, summary, "priceIrr", "sortOrder")
  VALUES
    ('sm-pos',   cid, 'pos',        'صندوق فروشگاهی',
     'بارکد، ترازو، شیفت صندوق‌دار، کالای وزنی و کار در حالت آفلاین.', 48000000, 1),
    ('sm-resto', cid, 'restaurant', 'کافه و رستوران',
     'میز و سالن، منو و رسپی، نمایشگر آشپزخانه، رزرو و تقسیم صورتحساب.', 52000000, 2),
    ('sm-shop',  cid, 'shop',       'فروشگاه اینترنتی',
     'کاتالوگ عمومی، سبد خرید، سفارش مشتری، نظرات خریداران و پیگیری سفارش.', 39000000, 3),
    ('sm-wh',    cid, 'warehouse',  'انبار و خرید',
     'چند انباره، انتقال، شمارش، بهای تمام‌شدهٔ میانگین موزون و پیشنهاد سفارش.', 35000000, 4),
    ('sm-acc',   cid, 'accounting', 'حسابداری',
     'دفتر کل دوطرفه، خزانه، چک، دارایی و استهلاک، و صورت‌های مالی.', 58000000, 5),
    ('sm-hr',    cid, 'hr',         'منابع انسانی',
     'حضور و غیاب، حقوق و دستمزد، مرخصی، آموزش و ارزیابی عملکرد.', 31000000, 6)
  ON CONFLICT ("companyId", slug) DO NOTHING;
END $$;
