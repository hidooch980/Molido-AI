-- بهای تمام‌شدهٔ هر سطرِ فروش، در لحظهٔ فروش.
--
-- ⚠️ چرا لازم شد؟
--
--    از مهاجرت ۰۴۶، فروش با میانگین موزونِ انبار خرج می‌خورد.  ولی
--    مرجوعی همچنان از `Product."purchasePrice"` می‌خواند
--    (`returns.service.ts`).
--
--    یعنی فروشی که با میانگینِ ۱۵۰۰ خرج خورده، اگر بینِ فروش و
--    مرجوعی یک خریدِ گران ثبت شده باشد، با ۲۰۰۰ برگشت می‌خورد.
--    اختلافِ ۵۰۰ در دفتر کل **برای همیشه** می‌ماند.
--
--    پیش از ۰۴۶ هر دو سمت غلطِ یکسان بودند، پس خنثی می‌شدند.  حالا
--    که یک سمت درست شده، نبودِ این ستون وضع را از قبل بدتر می‌کرد.
--
-- ⚠️ چرا ستونِ ثبت‌شده و نه محاسبهٔ دوباره هنگام مرجوعی؟
--
--    بهای میانگین با هر خرید عوض می‌شود.  هر محاسبهٔ دوباره‌ای —
--    هر قدر هم دقیق — عددِ *امروز* را می‌دهد، نه عددی که آن فاکتور
--    با آن خرج خورد.  تنها راهِ تضمینِ خنثی شدنِ کامل، نگاه کردنِ
--    هر دو سمت به **یک عددِ ثبت‌شده** است.
--
--    همین ستون گزارشِ سودِ فروش را هم درست می‌کند: سودِ فروشِ پارسال
--    باید با بهای پارسال حساب شود، نه با بهای امروز.
--
-- ⚠️ تهی یعنی «فروشِ پیش از این تغییر».
--
--    برای آن‌ها راهی جز عقب‌گرد به `purchasePrice` نیست — تاریخچهٔ
--    واقعی‌شان را نداریم.  همان رفتارِ قبلی، پس هیچ عددی جابه‌جا
--    نمی‌شود.
ALTER TABLE "SaleItem"
  ADD COLUMN IF NOT EXISTS "unitCost" numeric;

COMMENT ON COLUMN "SaleItem"."unitCost" IS
  'بهای تمام‌شدهٔ واحد در لحظهٔ فروش.  مرجوعی و گزارشِ سود به همین تکیه می‌کنند؛ تهی = فروشِ پیش از مهاجرت ۰۴۸.';

ALTER TABLE "SaleItem"
  DROP CONSTRAINT IF EXISTS "SaleItem_unitCost_nonneg";
ALTER TABLE "SaleItem"
  ADD CONSTRAINT "SaleItem_unitCost_nonneg"
  CHECK ("unitCost" IS NULL OR "unitCost" >= 0);
