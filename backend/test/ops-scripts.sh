#!/usr/bin/env bash
#
# سلامتِ اسکریپت‌های عملیات — از جمله متنی که به سرور فرستاده می‌شود.
#
# ⚠️ `bash -n` کافی نیست، و این را با یک ایرادِ واقعی یاد گرفتیم.
#
#    `set-subdomains.sh` سه آرگومان می‌فرستاد ولی متنِ راه‌دور `$4` را
#    می‌خواند.  نحو کاملاً درست بود و `bash -n` سبز می‌داد؛ ولی با
#    `set -eu` استقرار در خطِ پنجم `unbound variable` می‌گرفت و هرگز
#    شروع نمی‌شد.
#
#    تنها راهِ گرفتنش، **اجرای** متنِ راه‌دور با آرگومان‌های نمونه است.
#
# ⚠️ و متنِ راه‌دور جدا سنجیده می‌شود، نه فایلِ بیرونی.
#
#    آنچه روی سرور اجرا می‌شود همان چیزی است که داخلِ heredoc است.
#    سنجشِ فایلِ بیرونی دربارهٔ آن هیچ نمی‌گوید.

cd "$(dirname "$0")/../.." || exit 1

pass=0; fail=0
chk() { if [ "$2" = "$3" ]; then pass=$((pass+1)); printf '  OK   %s\n' "$1"; else fail=$((fail+1)); printf '  FAIL %s (got=%s want=%s)\n' "$1" "$2" "$3"; fi; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo '--- ۱) نحوِ همهٔ اسکریپت‌ها ---'
BAD=""
for f in ops/*.sh backend/test/*.sh; do
  bash -n "$f" 2>/dev/null || BAD="$BAD $(basename "$f")"
done
chk "همه از نظر نحوی سالم‌اند" "${BAD:-none}" "none"

echo '--- ۲) متنِ راه‌دورِ heredoc ---'
#
# هر اسکریپتی که `bash -s` دارد، متنِ داخلش جدا بیرون کشیده و سنجیده
# می‌شود — هم نحو، هم آرگومان‌هایی که واقعاً فرستاده می‌شوند.
for f in ops/*.sh; do
  grep -q 'bash -s' "$f" || continue
  name=$(basename "$f")

  awk '/<<.REMOTE_SCRIPT.$/{f=1;next} /^REMOTE_SCRIPT$/{f=0} f' "$f" > "$TMP/inner.sh"
  [ -s "$TMP/inner.sh" ] || continue

  chk "$name: متنِ راه‌دور نحوش درست است" \
    "$(bash -n "$TMP/inner.sh" 2>/dev/null && echo ok || echo bad)" "ok"

  # ⚠️ **سنجهٔ اصلی.**
  #
  #    بالاترین شمارهٔ `$N` که متن می‌خواند نباید از تعدادِ
  #    آرگومان‌هایی که `bash -s --` می‌فرستد بیشتر باشد.
  #    ⚠️ فقط **انتساب‌های سطحِ بالا** شمرده می‌شوند (`VAR="$1"`)،
  #       نه هر `$N`ی در فایل.
  #
  #       نسخهٔ اول همه را می‌شمرد و `$3` داخلِ تابعِ `chk` را — که
  #       پارامترِ خودِ تابع است، نه آرگومانِ اسکریپت — به حساب
  #       می‌آورد.  نتیجه‌اش قرمزیِ کاذب روی `verify-restore.sh` بود
  #       که کاملاً سالم است.
  #
  #       گرفتنِ آرگومانِ اسکریپت همیشه همین شکل را دارد، پس این الگو
  #       هم کافی است و هم مثبتِ کاذب نمی‌سازد.
  NEEDS=$(grep -oE '^[A-Za-z_][A-Za-z0-9_]*="\$[1-9]"' "$TMP/inner.sh" | grep -oE '[1-9]' | sort -n | tail -1)
  #
  #    ⚠️ شمارش **پس از** `--` شروع می‌شود، نه از اولِ خط.
  #
  #       نسخهٔ اول کلِ دو خط را می‌شمرد و `"$HOST"` را — که میزبانِ
  #       ssh است، نه آرگومانِ اسکریپت — جزو آرگومان‌ها می‌آورد.
  #       نتیجه: شمارشِ یکی بیشتر، و نگهبان همان ایرادی را که برای
  #       گرفتنش نوشته شده بود از دست می‌داد.  با تزریقِ عمدیِ خطا
  #       سنجیده شد.
  SENDS=$(grep 'bash -s --' -A1 "$f"           | tr '
' ' '           | sed 's/.*bash -s -- *//; s/<<.*//'           | grep -oE '"[^"]*"' | wc -l)

  chk "$name: آرگومان‌های کافی فرستاده می‌شود" \
    "$([ "${SENDS:-0}" -ge "${NEEDS:-0}" ] && echo yes || echo "no (می‌خواهد ${NEEDS:-?}، می‌فرستد ${SENDS:-?})")" "yes"
done

echo '--- ۳) اسکریپت‌های عملیات اجرایی‌اند ---'
# ⚠️ فایلی که اجرایی نیست، با `bash x.sh` کار می‌کند ولی با `./x.sh`
#    نه — و دستورالعمل‌ها معمولاً شکلِ دوم را می‌نویسند.
NOEXEC=""
for f in ops/*.sh; do
  [ -x "$f" ] || NOEXEC="$NOEXEC $(basename "$f")"
done
chk "همه اجرایی‌اند" "${NOEXEC:-none}" "none"

echo '--- ۴) پول جابه‌جا می‌شود، دفتر خبر دارد؟ ---'
#
# ⚠️ این نگهبان از یک روز جست‌وجوی دستی درآمد — و برای این نوشته شده
#    که آن جست‌وجو دوباره لازم نشود.
#
#    چهار جا موجودی را عوض می‌کردند و هیچ سندی نمی‌زدند:
#      • واریز/برداشتِ صندوق  (نه سند، نه ردِ حسابرسی)
#      • واریز/برداشتِ خزانه   (ردِ حسابرسی داشت، سند نه)
#      • وصولِ مشتری           (مطالبات هرگز تسویه نمی‌شد)
#      • تسویهٔ رستوران        (۱۹ میلیون فروش بیرونِ دفتر)
#
#    و هیچ‌کدام با آزمون پیدا نشد، چون **تراز آزمایشی صفر می‌ماند**:
#    وقتی سندی زده نمی‌شود، چیزی هم نامتراز نمی‌شود.  تنها راه، همین
#    سنجهٔ ایستا بود.
#
# ⚠️ سنجه ایستا است و ادعای قطعی نمی‌کند.
#
#    «فایلی که موجودی را عوض می‌کند ولی هیچ ارجاعی به سند ندارد» یک
#    **نشانه** است نه اثبات.  استثناها نام‌دارند و دلیل دارند؛ هر نامِ
#    تازه‌ای که اینجا اضافه شود باید دلیلش هم نوشته شود.
#
#   ration — سهمیهٔ یارانه‌ایِ مشتری است نه پولِ شرکت، و داخلِ تراکنشِ
#            خودِ فروش خرج می‌شود (`spendIn` با `saleId`)، پس سندش با
#            سندِ فروش می‌خورد.  سنجیده شد.
LEDGER_EXEMPT="ration"

UNPOSTED=""
for f in $(grep -rl 'balance = balance' backend/src --include=*.ts 2>/dev/null); do
  base=$(basename "$f" .service.ts)
  case " $LEDGER_EXEMPT " in *" $base "*) continue ;; esac
  # ⚠️ الگو **فراخوانی** را می‌سنجد، نه نامِ ماژول را.
  #
  #    نسخهٔ اول `posting\.` را می‌گرفت و خطِ
  #    `import ... '../accounting/posting.service'` را هم «سند زدن»
  #    می‌شمرد.  نتیجه: با تزریقِ عمدیِ خطا هم سبز ماند — نگهبانی که
  #    فقط وجودِ import را می‌دید، نه اینکه سندی زده می‌شود.
  grep -qE 'postAuto\(|postIn\(' "$f" || UNPOSTED="$UNPOSTED $base"
done

chk "هر جابه‌جاییِ موجودی سند می‌زند" "${UNPOSTED:-none}" "none"

if [ -n "$UNPOSTED" ]; then
  echo
  echo "     این فایل‌ها موجودی را عوض می‌کنند ولی سندی نمی‌زنند."
  echo "     یا سند را وصل کنید، یا با دلیل به LEDGER_EXEMPT اضافه کنید."
fi

echo
printf "   PASS: %s   FAIL: %s\n" "$pass" "$fail"
exit $([ "$fail" -eq 0 ] && echo 0 || echo 1)
