-- قابلیت‌های هر نسخهٔ فروش
--
-- ⚠️ تا امروز سه نسخهٔ پایه/حرفه‌ای/پیشرفته فقط **سقفِ کاربر و شعبه** را
--    محدود می‌کردند.
--
--    یعنی مشتریِ «پایه» رستوران، فروشگاه اینترنتی، CRM و خزانه را هم
--    می‌گرفت.  سه نسخه روی کاغذ بود و در عمل یکی — و چیزی برای فروختن
--    نمی‌ماند جز شمارِ کاربر.
--
-- ⚠️ دانه‌بندی همان `FeatureKey`ِ `product.ts` است، نه فهرستی تازه.
--
--    دو فهرستِ موازیِ ماژول یعنی روزی یکی به‌روز می‌شود و دیگری نه، و
--    قابلیتی که فروخته شده کار نمی‌کند — یا برعکس، قابلیتی که فروخته
--    نشده کار می‌کند.

ALTER TABLE "PlanDefault" ADD COLUMN IF NOT EXISTS features JSONB;

-- ⚠️ NULL یعنی «بی‌حد»، مثل `maxUsers`.
--
--    همان قاعدهٔ ۰۷۱: صفر قفل می‌کند، NULL باز می‌گذارد.  آرایهٔ خالی
--    هم قفل است — پس نسخه‌ای که هنوز تعریف نشده باید NULL بماند، نه
--    `[]`، وگرنه مشتریانش از کار می‌افتند.
COMMENT ON COLUMN "PlanDefault".features IS
  'آرایهٔ FeatureKey؛ NULL یعنی همه';

-- ---------- نسخهٔ پایه ----------
--
-- ⚠️ `catalogue` و `sales` هستهٔ هر کسب‌وکارِ کالایی‌اند و بدونشان
--    نرم‌افزار کار نمی‌کند.  `retail` هم هست چون صندوقِ فروشگاهی همان
--    چیزی است که مشتریِ پایه می‌خرد.
UPDATE "PlanDefault"
   SET features = '["catalogue","sales","retail"]'::jsonb
 WHERE plan = 'BASIC';

-- ---------- حرفه‌ای ----------
--
-- خزانه و چک و قرارداد، CRM، و منابع انسانی — چیزهایی که کسب‌وکارِ
-- چندشعبه‌ای لازم دارد.
UPDATE "PlanDefault"
   SET features = '["catalogue","sales","retail","finance","crm","hr"]'::jsonb
 WHERE plan = 'PRO';

-- ---------- پیشرفته ----------
--
-- NULL یعنی بی‌حد — رستوران، فروشگاه اینترنتی، کالابرگ و هر چیزی که
-- بعداً افزوده شود، بدونِ نیاز به مهاجرتِ تازه.
UPDATE "PlanDefault" SET features = NULL WHERE plan = 'ADVANCED';

-- ---------- اشتراکِ موجود ----------
--
-- ⚠️ هیچ مشتریِ فعلی نباید قابلیتی را از دست بدهد.
--
--    مهاجرت ۰۷۱ همهٔ شرکت‌های موجود را ADVANCED گذاشت، و ADVANCED
--    بی‌حد است — پس این مهاجرت برای هیچ نصبی چیزی را نمی‌بندد.
--
--    این عمدی است: مهاجرتی که روزِ استقرار قابلیتی را از مشتری بگیرد،
--    همان روز تماسِ پشتیبانی می‌سازد.  بستنِ قابلیت تصمیمِ فروش است و
--    باید دستی و آگاهانه انجام شود.
