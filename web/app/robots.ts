import type { MetadataRoute } from 'next';

// ⚠️ بدونِ این، Next فایل را در زمانِ **ساخت** تولید و منجمد می‌کند و
//    `SITE_URL`ِ زمانِ اجرا هیچ اثری ندارد — دقیقاً همان چیزی که
//    می‌خواستیم از آن فرار کنیم.
export const dynamic = 'force-dynamic';

/**
 * `robots.txt` — چه چیزی ایندکس شود و چه چیزی نه.
 *
 * ⚠️ چرا لازم بود؟
 *
 *    تا امروز فایلی نبود.  یعنی خزنده هر مسیری را که پیدا می‌کرد
 *    می‌خزید — از جمله پنلِ مدیریت و صفحه‌های شخصیِ مشتری.
 *
 *    آن صفحه‌ها پشتِ ورود‌اند و داده‌ای لو نمی‌دهند، ولی دو زیان دارند:
 *    سهمیهٔ خزشِ سایت را روی صفحه‌های بی‌فایده خرج می‌کنند، و مسیرهایی
 *    مثل `/shop/account` ممکن است در نتایج ظاهر شوند و کاربر را به
 *    صفحهٔ ورود بفرستند به‌جای کالا.
 *
 * ⚠️ `disallow` جایگزینِ کنترلِ دسترسی **نیست**.
 *
 *    فقط خزندهٔ مؤدب را متوقف می‌کند.  محافظتِ واقعی همان بررسیِ
 *    توکن در سرور است که از قبل هست؛ این فقط سئو را مرتب می‌کند.
 */
export default function robots(): MetadataRoute.Robots {
  // ⚠️ `SITE_URL` اول خوانده می‌شود، بعد `NEXT_PUBLIC_SITE_URL`.
  //
  //    این فایل روی **سرور** اجرا می‌شود، پس متغیرِ معمولی را در زمانِ
  //    اجرا می‌خواند.  `NEXT_PUBLIC_*` برعکس، هنگامِ ساخت در باندل
  //    جاسازی می‌شود — یعنی برای عوض کردنِ دامنه باید ایمیج را دوباره
  //    ساخت.  برای چیزی که در استقرار تعیین می‌شود، آن رفتار غلط است.
  const base = (process.env.SITE_URL || process.env.NEXT_PUBLIC_SITE_URL)
    ?.replace(/\/+$/, '');

  return {
    rules: [
      {
        userAgent: '*',
        // ⚠️ ریشه صریحاً مجاز است.
        //
        //    تا امروز `/` صفحهٔ ورودِ پنل بود و ایندکسش بی‌معنا.  حالا
        //    صفحهٔ معرفیِ شرکت است و **مهم‌ترین** صفحه‌ای که باید
        //    ایندکس شود.
        allow: ['/', '/shop', '/shop/product/'],
        disallow: [
          // صفحه‌های شخصیِ مشتری — محتوایشان برای هر کاربر فرق دارد
          // و ایندکسشان بی‌معناست.
          '/shop/cart',
          '/shop/account',
          '/shop/orders',
          '/shop/login',
          // کلِ پنلِ کارکنان.
          //
          // ⚠️ `/panel` باید اینجا باشد: صفحهٔ ورود از وقتی ریشه به
          //    معرفیِ شرکت داده شد، به این مسیر منتقل شد.  ایندکسِ
          //    فرمِ رمز نه فایده دارد نه امن است.
          '/panel',
          '/dashboard',
          '/pos',
          '/products',
          '/inventory',
          '/sales',
          '/purchases',
          '/accounting',
          '/reports',
          '/settings',
          '/users',
          '/records',
          '/restaurant',
          '/api/',
        ],
      },
    ],
    // ⚠️ بدونِ نشانیِ مطلق، نقشهٔ سایت اعلام نمی‌شود.
    //    اگر `NEXT_PUBLIC_SITE_URL` تنظیم نشده باشد، سطر حذف می‌شود
    //    نه اینکه نشانیِ غلط بدهد.
    ...(base ? { sitemap: `${base}/sitemap.xml` } : {}),
  };
}
