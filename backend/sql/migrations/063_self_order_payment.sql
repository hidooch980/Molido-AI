-- پرداختِ آنلاینِ سفارشِ سرِ میز.
--
-- ⚠️ `paymentRef` روی خودِ سفارش می‌نشیند، نه در جدولِ جدا.
--
--    وسوسه این بود که `SelfOrderPayment` ساخته شود تا چند تلاشِ
--    پرداخت ثبت شود.  ولی تأیید همیشه با **آخرین** ارجاع انجام
--    می‌شود و سفارش هم یکی است؛ جدولِ دوم فقط جایی می‌شد که
--    «کدام ارجاع معتبر است؟» بتواند غلط جواب بدهد.
--
--    هر تلاشِ تازه ارجاعِ قبلی را بازنویسی می‌کند.  ارجاعِ سوخته دیگر
--    نزدِ درگاه معتبر نیست، پس چیزی از دست نمی‌رود.
ALTER TABLE "RestaurantOrder"
  ADD COLUMN IF NOT EXISTS "paymentRef" text;

-- شمارهٔ پیگیریِ بانک — چیزی که مشتری با آن به بانکش مراجعه می‌کند.
ALTER TABLE "RestaurantOrder"
  ADD COLUMN IF NOT EXISTS "bankRef" text;

-- ⚠️ `paidAt` جدا از `closedAt` است و این تفاوت مهم است.
--
--    `closedAt` یعنی «میز آزاد شد»، `paidAt` یعنی «پول رسید».  در
--    پیش‌پرداخت این دو فاصله دارند: مشتری پیش از غذا خوردن پرداخت
--    می‌کند و میز ساعتی بعد آزاد می‌شود.  یکی گرفتنشان گزارشِ درآمدِ
--    روزانه را به تاریخِ اشتباه می‌برد.
ALTER TABLE "RestaurantOrder"
  ADD COLUMN IF NOT EXISTS "paidAt" timestamptz;
