-- حذفِ `companyId` از `GovSsoState`.
--
-- ⚠️ چرا؟  نگهبانِ `integration` درست گرفتش.
--
--    سنجهٔ «every companyId table protected» می‌گوید هر جدولی که
--    `companyId` دارد باید سیاستِ جداسازی داشته باشد.  این یکی نداشت.
--
--    مهاجرتِ ۰۵۴ در کامنتش استدلال کرده بود که «سطرِ state توکنِ گذرا
--    است نه دادهٔ شرکت» — ولی آن استدلال، قاعده را دور می‌زد نه اینکه
--    برآورده‌اش کند.  و افزودنِ سیاستِ معمولی هم کار نمی‌کرد: جریان
--    پیش از ورود شروع می‌شود، `app.company_id` تهی است، و
--    fail-closed یعنی هیچ سطری — دقیقاً همان دامی که پیگیریِ شکایت
--    را از کار انداخته بود.
--
-- ⚠️ راهِ درست: ستون اصلاً لازم نبود.
--
--    مقدارش فقط از `SHOP_COMPANY_ID` می‌آمد — پیکربندیِ سرور، نه
--    دادهٔ کاربر — و در لحظهٔ بازگشت هم به همان شکل در دسترس است.
--    ذخیره‌اش نه چیزی اضافه می‌کرد و نه امن‌تر بود؛ فقط یک نسخهٔ
--    دومِ همان مقدار می‌ساخت که می‌توانست کهنه شود.
--
--    `ShopTenantMiddleware` هم فقط روی مسیرهای `shop` سوار است، پس
--    `req.shopCompanyId` در این کنترلر هرگز پر نمی‌شد — کدی که
--    می‌خواندش، خواندنی از چیزی بود که همیشه تهی است.

ALTER TABLE "GovSsoState" DROP COLUMN IF EXISTS "companyId";
