-- کوتاه کردنِ مقیاسِ میانگین موزون.
--
-- ⚠️ چرا لازم شد؟
--
--    تقسیمِ `numeric` در پستگرس مقیاسِ نامحدود می‌دهد.  فرمولِ
--    میانگین در `applyStockDelta` تقسیم دارد، پس `avgCost` با ده‌ها
--    رقمِ اعشار ذخیره می‌شد:
--
--      248485.4610069351329794570449026098236503769747778844
--
--    و چون `stockValue` انبار از ضربِ همین عدد می‌آید، پاسخِ API به
--    شکلِ «۶۸۷۱۴۳۶۳۹۵.۱۷۴۹۷۶۸۳۲۶۱۳۶۷۹۷۶۸۶۰۱۳۵۷۳۰۶...» برمی‌گشت.
--
--    خودِ فرمول اصلاح شد؛ این مهاجرت ردیف‌هایی را که پیش از آن نوشته
--    شده‌اند مرتب می‌کند.  شش رقم برای بهای واحد بیش از کافی است و
--    خطای گردکردنش در ضربِ موجودی بی‌اثر است.
UPDATE "Inventory"
   SET "avgCost" = round("avgCost", 6)
 WHERE "avgCost" IS NOT NULL
   AND scale("avgCost") > 6;
