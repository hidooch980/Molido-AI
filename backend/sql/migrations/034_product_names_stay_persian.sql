-- =============================================
-- نام کالا در پیکرهٔ صوتی، فارسی می‌ماند
--
-- صندوق‌دار بلوچ هم «شامپو» را «شامپو» می‌گوید — نام کالا وام‌واژه
-- است، نه واژهٔ زبان.  منتظر ماندن برای ترجمه‌ای که هیچ‌وقت نمی‌آید،
-- نام کالاها را برای همیشه از صف ضبط بیرون نگه می‌داشت: بدون متن
-- هدف، گوینده نمی‌داند چه بگوید و آن عبارت هرگز ضبط نمی‌شود.
--
-- ضبطشان هنوز لازم است — مدل باید همان نام فارسی را با لهجهٔ بلوچی
-- بشناسد، که با تلفظ فارسی‌زبان یکی نیست.
--
-- عدد و فرمان عمداً دست‌نخورده می‌مانند: «سه» در بلوچی «سئی» است، و
-- پر کردنشان با فارسی یعنی مدل چیز اشتباهی یاد می‌گیرد.
-- =============================================

UPDATE "VoicePhrase"
   SET "textTarget" = "textFa"
 WHERE kind = 'PRODUCT'
   AND "textTarget" IS NULL;
