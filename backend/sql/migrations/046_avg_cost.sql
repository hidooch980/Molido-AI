-- بهای تمام‌شدهٔ میانگین موزون — روی خودِ موجودی.
--
-- ⚠️ چه چیزی غلط بود؟
--
--    بهای تمام‌شدهٔ فروش از `Product."purchasePrice"` می‌آمد — یک عددِ
--    واحد که هنگام دریافتِ خرید **بازنویسی** می‌شد.  یعنی:
--
--    ۱. بهای همهٔ واحدهای فروخته‌شده با قیمتِ *آخرین* خرید حساب
--       می‌شد، نه بهای کالایی که واقعاً در انبار بود.  صد کارتن
--       خریده به ۱۰۰۰، ده کارتنِ تازه به ۲۰۰۰ ⇒ فروشِ بعدی همه‌اش
--       ۲۰۰۰ حساب می‌شد و سودِ ناخالص کمتر از واقع گزارش می‌شد.
--
--    ۲. بدتر: به‌روزرسانی فقط وقتی رخ می‌داد که کرایهٔ حمل داشته
--       باشد (`if (share === 0) continue`).  خریدِ بی‌کرایه اصلاً
--       بهای کالا را به‌روز نمی‌کرد.
--
--    ۳. و چون روی `Product` بود نه موجودی، انبارهای مختلف با بهای
--       متفاوت یک عدد مشترک داشتند.
--
-- ⚠️ چرا روی `Inventory` و نه `Product`؟
--
--    بها به «این کالا در این انبار» تعلق دارد.  همان کالا که با
--    کرایهٔ متفاوت به دو انبار رسیده، دو بهای تمام‌شدهٔ متفاوت دارد —
--    و گزارشِ سودِ هر شعبه باید همان را ببیند.
--
-- ⚠️ تهی یعنی «هنوز بهایی ثبت نشده»، نه صفر.
--
--    صفر یک بهای واقعی است (کالای اهدایی).  اگر پیش‌فرض صفر بود،
--    موجودیِ قدیمیِ بی‌بها با سودِ صددرصد گزارش می‌شد.  تهی به
--    محاسبه می‌گوید به `purchasePrice` عقب‌گرد کن.
ALTER TABLE "Inventory"
  ADD COLUMN IF NOT EXISTS "avgCost" numeric;

COMMENT ON COLUMN "Inventory"."avgCost" IS
  'میانگین موزونِ بهای تمام‌شده در این انبار.  تهی = هنوز ثبت نشده؛ به purchasePrice عقب‌گرد کن.';

-- ⚠️ بهای منفی معنا ندارد و نشانهٔ اشکالِ محاسبه است.
--
--    قید در سطح پایگاه داده می‌گذاریم، نه فقط در کد: اگر روزی
--    فرمولِ میانگین اشتباه شود، باید همان‌جا بشکند — نه اینکه ماه‌ها
--    بعد در صورتِ سود و زیان دیده شود.
ALTER TABLE "Inventory"
  DROP CONSTRAINT IF EXISTS "Inventory_avgCost_nonneg";
ALTER TABLE "Inventory"
  ADD CONSTRAINT "Inventory_avgCost_nonneg"
  CHECK ("avgCost" IS NULL OR "avgCost" >= 0);

-- ------------------------------------------- مقداردهیِ اولیه

-- ⚠️ موجودیِ موجود بی‌بها می‌ماند اگر کاری نکنیم.
--
--    بهترین تخمینِ در دسترس برای کالای از قبل در انبار، همان
--    `purchasePrice` فعلی است.  دقیق نیست — تاریخچهٔ واقعی را
--    نداریم — ولی از تهی بهتر است و رفتار را با قبل یکی می‌کند،
--    پس مهاجرت هیچ عددی را ناگهان تغییر نمی‌دهد.
UPDATE "Inventory" i
   SET "avgCost" = round(p."purchasePrice", 6)
  FROM "Product" p
 WHERE p.id = i."productId"
   AND i."avgCost" IS NULL
   AND p."purchasePrice" IS NOT NULL
   AND p."purchasePrice" >= 0;
