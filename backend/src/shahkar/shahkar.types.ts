/**
 * نتیجهٔ استعلامِ شاهکار.
 *
 * ⚠️ سه حالت، نه دو حالت.
 *
 *    «تطبیق دارد» و «تطبیق ندارد» کافی نیست: حالتِ سوم «نتوانستیم
 *    بفهمیم» است — سرویس در دسترس نبود، سهمیه تمام شد، پاسخ بدریخت
 *    بود.  اگر این با «تطبیق ندارد» یکی شمرده شود، قطعیِ سرویسِ
 *    دولتی به «کد ملیِ شما جعلی است» ترجمه می‌شود و کاربرِ درست
 *    بیرون می‌ماند.
 *
 *    و اگر با «تطبیق دارد» یکی شمرده شود، بدتر: قطعیِ سرویس به
 *    دورزدنِ کاملِ احرازِ هویت ترجمه می‌شود.
 */
export type ShahkarOutcome = 'MATCHED' | 'NOT_MATCHED' | 'UNKNOWN';

export type ShahkarResult = {
  outcome: ShahkarOutcome;

  /** پیامِ خواندنی برای کاربر. */
  message: string;

  /**
   * شناسهٔ پیگیریِ ارائه‌دهنده.
   *
   * وقتی کاربر می‌گوید «شمارهٔ من به نامِ خودم است»، تنها چیزی که
   * می‌شود با آن به ارائه‌دهنده مراجعه کرد همین است.
   */
  reference?: string;

  /**
   * استعلامِ واقعی انجام نشد و پاسخ ساختگی است.
   *
   * ⚠️ هرگز نباید با نتیجهٔ واقعی اشتباه شود.  همان الگوی
   *    `sms.service` و `zarinpal.gateway`.
   */
  simulated?: boolean;

  /** پیامِ خامِ ارائه‌دهنده — برای عیب‌یابی، نه برای کاربر. */
  raw?: string;
};
