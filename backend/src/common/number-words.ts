/**
 * عدد به حروفِ فارسی.
 *
 * ⚠️ روی چک **اجباری** است، و اجباری‌بودنش دلیلِ فنی دارد نه تشریفاتی:
 *    رقمِ ۱۰۰٬۰۰۰ را می‌شود با یک صفر به ۱٬۰۰۰٬۰۰۰ تبدیل کرد؛ «صد
 *    هزار» را نمی‌شود.  حروف، رقم را قفل می‌کند.
 *
 * ⚠️ پس این تابع جایی است که یک اشتباهِ کوچک، پولِ واقعی جابه‌جا
 *    می‌کند — و آزمونش باید همان‌قدر جدی باشد.
 *
 * ماژول عمداً خالص و بی‌وابستگی است تا هم در بک‌اند و هم در آزمونِ واحد
 * بدون پایگاه‌داده کار کند.
 */

const ONES = [
  '', 'یک', 'دو', 'سه', 'چهار', 'پنج', 'شش', 'هفت', 'هشت', 'نه',
];

const TEENS = [
  'ده', 'یازده', 'دوازده', 'سیزده', 'چهارده', 'پانزده',
  'شانزده', 'هفده', 'هجده', 'نوزده',
];

const TENS = [
  '', '', 'بیست', 'سی', 'چهل', 'پنجاه',
  'شصت', 'هفتاد', 'هشتاد', 'نود',
];

const HUNDREDS = [
  '', 'صد', 'دویست', 'سیصد', 'چهارصد', 'پانصد',
  'ششصد', 'هفتصد', 'هشتصد', 'نهصد',
];

/**
 * مقیاس‌های سه‌رقمی.
 *
 * ⚠️ «میلیارد» در فارسی رایج است، ولی بالاتر از آن نه.
 *    برای مبالغِ بزرگ‌تر، به‌جای ساختنِ واژه‌ای که کسی نمی‌فهمد، خطا
 *    داده می‌شود — روی چک، عبارتی که خوانده نشود از نبودش بدتر است.
 */
const SCALES = ['', ' هزار', ' میلیون', ' میلیارد'];

/** بزرگ‌ترین عددِ پشتیبانی‌شده: ۹۹۹ میلیارد و خرده. */
export const MAX_SUPPORTED = 1_000_000_000_000 - 1;

const SEPARATOR = ' و ';

/** یک گروهِ سه‌رقمی (۱ تا ۹۹۹) را به حروف می‌برد. */
function tripletToWords(n: number): string {
  const parts: string[] = [];

  const h = Math.floor(n / 100);
  const rest = n % 100;
  if (h > 0) parts.push(HUNDREDS[h]);

  if (rest >= 10 && rest <= 19) {
    parts.push(TEENS[rest - 10]);
  } else {
    const t = Math.floor(rest / 10);
    const o = rest % 10;
    if (t > 0) parts.push(TENS[t]);
    if (o > 0) parts.push(ONES[o]);
  }

  return parts.join(SEPARATOR);
}

/**
 * عدد را به حروفِ فارسی برمی‌گرداند.
 *
 * ⚠️ فقط عددِ **صحیحِ نامنفی**.  مبلغِ چک اعشار ندارد، و پذیرفتنِ
 *    اعشار یعنی «هزار و پانصدُم» ساختن که هیچ‌کس نمی‌نویسد.
 */
export function numberToPersianWords(value: number): string {
  if (!Number.isFinite(value)) {
    throw new Error('عدد معتبر نیست');
  }
  if (!Number.isInteger(value)) {
    throw new Error('مبلغ باید عددِ صحیح باشد');
  }
  if (value < 0) {
    throw new Error('مبلغ نمی‌تواند منفی باشد');
  }
  if (value > MAX_SUPPORTED) {
    throw new Error('مبلغ بزرگ‌تر از حدِ پشتیبانی‌شده است');
  }
  if (value === 0) return 'صفر';

  // گروه‌های سه‌رقمی، از کم‌ارزش به پرارزش.
  const groups: number[] = [];
  let n = value;
  while (n > 0) {
    groups.push(n % 1000);
    n = Math.floor(n / 1000);
  }

  const parts: string[] = [];
  // ⚠️ از پرارزش به کم‌ارزش خوانده می‌شود، پس معکوس پیمایش می‌شود.
  for (let i = groups.length - 1; i >= 0; i -= 1) {
    const g = groups[i];
    // گروهِ صفر اصلاً گفته نمی‌شود: «یک میلیون و بیست» نه
    // «یک میلیون و صفر هزار و بیست».
    if (g === 0) continue;
    parts.push(`${tripletToWords(g)}${SCALES[i]}`);
  }

  return parts.join(SEPARATOR);
}

/**
 * مبلغِ چک به حروف، با واحد.
 *
 * ⚠️ واحد **ریال** است، نه تومان.
 *
 *    مبالغ در سرتاسرِ این سامانه ریال‌اند و چکِ بانکی هم به ریال نوشته
 *    می‌شود.  اگر اینجا تومان نوشته شود، عددِ روی چک و حروفِ روی چک ده
 *    برابر اختلاف پیدا می‌کنند — و بانک چک را برمی‌گرداند، اگر خوش‌شانس
 *    باشیم.
 */
export function amountInWords(rial: number): string {
  return `${numberToPersianWords(rial)} ریال`;
}
