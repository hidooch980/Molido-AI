-- بهای تمام‌شدهٔ قلمِ سفارشِ رستوران — قفل‌شده در لحظهٔ سفارش.
--
-- ⚠️ همان اشکالی که برای `SaleItem` بسته شد، اینجا هنوز باز بود.
--
--    `RestaurantOrderItem` بها نداشت.  یعنی سودِ ناخالص — اگر روزی
--    حساب می‌شد — از بهای **امروزِ** قلمِ منو می‌آمد، نه بهای روزی که
--    فروخته شد.  قیمتِ گوشت که بالا برود، سودِ ماهِ گذشته هم عوض
--    می‌شود؛ گزارشی که دیروز چاپ کرده‌اید امروز عددِ دیگری می‌دهد.
--
-- ⚠️ و مسئلهٔ بزرگ‌تر: تا امروز درآمدِ رستوران **اصلاً** سند نمی‌خورد.
--
--    اندازه‌گیری شد: ۳۸ سفارشِ پرداخت‌شده با جمعِ ۱۹٬۲۴۰٬۰۰۰، و صفر
--    سند در دفترکل.  کلِ دفتر سه سند داشت، هر سه از حقوق و موجودیِ
--    افتتاحیه.  تراز آزمایشی هم صفر بود — چون وقتی سندی زده نمی‌شود،
--    چیزی هم نامتراز نمی‌شود.

ALTER TABLE "RestaurantOrderItem"
  ADD COLUMN IF NOT EXISTS "unitCost" numeric(18,2);

-- ⚠️ سطرهای گذشته عمداً پر **نمی‌شوند**.
--
--    وسوسه‌اش هست که با بهای امروزِ قلمِ منو پرشان کنیم.  ولی آن عدد
--    برای سفارشِ سه ماه پیش ساختگی است، و ساختگیِ **نامرئی** — چون
--    شبیه دادهٔ واقعی به نظر می‌رسد.
--
--    تهی ماندنشان صادقانه‌تر است: گزارش می‌تواند بگوید «بهای این
--    دوره ناشناخته است» به‌جای اینکه عددی بدهد که کسی رویش تصمیم
--    بگیرد.

CREATE INDEX IF NOT EXISTS "RestaurantOrderItem_orderId_idx"
  ON "RestaurantOrderItem" ("orderId");
