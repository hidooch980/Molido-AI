-- نمایه روی کلیدهای خارجیِ بی‌نمایه.
--
-- ⚠️ این خرابیِ **فردا**ست که امروز ارزان اصلاح می‌شود.
--
--    پستگرس برای کلیدِ خارجی خودکار نمایه نمی‌سازد — فقط برای کلیدِ
--    اصلی و قیدِ یکتا.  تا وقتی جدول کوچک است، هیچ اثری ندارد و هیچ
--    آزمونی هم نمی‌گیردش.
--
--    ولی دو چیز با رشدِ داده کند می‌شوند:
--
--      ۱. **حذف یا به‌روزرسانیِ سطرِ والد.**  پستگرس باید مطمئن شود
--         فرزندی نمانده، و بی‌نمایه یعنی اسکنِ کلِ جدولِ فرزند.
--         حذفِ یک مشتری با صد هزار فاکتور، کلِ `Sale` را می‌خوانَد.
--
--      ۲. **`JOIN` از سمتِ فرزند.**  `SaleItem.saleId` بی‌نمایه یعنی
--         باز کردنِ یک فاکتور، همهٔ اقلامِ همهٔ فاکتورها را اسکن کند.
--
--    امروز پایگاه‌داده ۱۷ مگابایت است و هیچ‌کدام دیده نمی‌شود.  با ده
--    برابر شدنِ داده، هر دو ناگهان ظاهر می‌شوند — و آن وقت ساختنِ
--    نمایه روی جدولِ بزرگ، خودش قفلِ طولانی می‌خواهد.
--
-- ⚠️ فهرست **از خودِ پایگاه‌داده** ساخته می‌شود، نه دستی.
--
--    فهرستِ دستی با هر جدولِ تازه کهنه می‌شود و کسی به‌روزش نمی‌کند.
--    این حلقه هر بار که اجرا شود، هر کلیدِ خارجیِ بی‌نمایه‌ای را —
--    از جمله آن‌هایی که فردا اضافه شوند — پوشش می‌دهد.
--
-- ⚠️ فقط ستونِ **اولِ** کلید بررسی می‌شود.
--
--    برای کلیدِ چندستونی، نمایه‌ای که با همان ستون شروع شود کافی
--    است — پستگرس از پیشوندِ نمایه استفاده می‌کند.  همان منطقی که
--    `pg_index.indkey` در پرس‌وجوی زیر پیاده می‌کند.

DO $$
DECLARE
  fk       record;
  idx_name text;
  n        int := 0;
BEGIN
  FOR fk IN
    SELECT t.relname AS tbl,
           a.attname AS col
      FROM pg_constraint c
      JOIN pg_class     t ON t.oid = c.conrelid
      JOIN pg_namespace ns ON ns.oid = t.relnamespace
      JOIN pg_attribute a ON a.attrelid = c.conrelid
                         AND a.attnum   = c.conkey[1]
     WHERE c.contype = 'f'
       AND ns.nspname = 'public'
       AND NOT EXISTS (
         SELECT 1 FROM pg_index i
          WHERE i.indrelid = c.conrelid
            AND c.conkey[1] = ANY(i.indkey)
       )
  LOOP
    -- نامِ قابلِ پیش‌بینی، تا اجرای دوباره چیزی تکراری نسازد.
    idx_name := fk.tbl || '_' || fk.col || '_idx';

    -- ⚠️ `IF NOT EXISTS` لازم است حتی با شرطِ بالا.
    --
    --    ممکن است نمایه‌ای با همین نام از قبل باشد ولی روی ستونِ
    --    دیگری — آن‌وقت `CREATE` بدونِ این شرط، کلِ مهاجرت را
    --    می‌شکند و بقیهٔ نمایه‌ها هم ساخته نمی‌شوند.
    EXECUTE format(
      'CREATE INDEX IF NOT EXISTS %I ON public.%I (%I)',
      idx_name, fk.tbl, fk.col
    );

    n := n + 1;
  END LOOP;

  RAISE NOTICE 'نمایهٔ ساخته‌شده روی کلید خارجی: %', n;
END $$;
